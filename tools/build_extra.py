"""Build the image26 actions both sets share: plugin/assets/extra/ and plugin/hooks/frames-extra.ts.

image26-v1/<action>/ already holds the frames at the plugin's own sizes and
baseline: <n>.png (186x184, the pane's full figure) and <n>-bust.png
(130x125, the band's head and shoulders). They are copied as they are.
The character cells are built here, the way tools/build_frames.py builds a
set's, with a palette of their own; register.tsx sets each action's timing.

Usage (needs Pillow and NumPy):
    uv run --with pillow --with numpy python tools/build_extra.py [image26-v1]
"""

from __future__ import annotations

import base64
import json
import shutil
import sys
from pathlib import Path

import numpy as np
from PIL import Image

from build_frames import PALETTE_COLORS, ROOT, SIZES, best_cells, quad_pixels, state_box

# state name in the mod -> action folder in image26-v1. image26's own idle is
# 'idle-1' here: 'idle' stays each set's original, which joins the rotation.
ACTIONS = {
    "idle-1": "idle",
    "idle-2": "idle-2",
    "idle-3": "idle-3",
    "idle-blink": "idle-blink",
    "hum": "hum",
    "clawd": "clawd",
    "yawn": "yawn",
    "sleeping-2": "sleeping-2",
    "stretch": "stretch",
    "surprised": "surprised",
    "pat-2": "pat-2",
    "coaxed": "coaxed",
    "redhot": "redhot",
    "annoyed": "annoyed",
    "forgiven": "forgiven",
    "thinking": "thinking",
    "searching": "searching",
    "writing": "writing",
    "busy_left": "busy_left",
    "busy_right": "busy_right",
    "delegating": "delegating",
    "swamped_left": "swamped_left",
    "swamped_right": "swamped_right",
    "tired": "tired",
    "listening": "listening",
    "proud": "proud",
    "happy-2": "happy-2",
    "oops": "oops",
    "sulk": "sulk",
    "dizzy": "dizzy",
    "sorry": "sorry",
    "compact": "compact",
}


def frame_paths(folder: Path) -> list[Path]:
    full = [p for p in folder.glob("*.png") if p.stem.isdigit()]
    return sorted(full, key=lambda p: int(p.stem))


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "image26-v1"
    asset_dir = ROOT / "plugin" / "assets" / "extra"
    if asset_dir.exists():
        shutil.rmtree(asset_dir)

    cells: dict[str, dict[str, list]] = {}
    for state, action in ACTIONS.items():
        paths = frame_paths(src / action)
        assert paths, f"{src / action}: no frames"
        frames = [Image.open(p).convert("RGBA") for p in paths]
        size = frames[0].size
        assert all(f.size == size for f in frames), f"{action}: frames differ in size"
        boxes = {"big": (0, 0, *size), "small": state_box((0, 0, *size), "small", frames)}
        cells[state] = {
            view: [best_cells(quad_pixels(f, boxes[view], cols, rows), cols, rows) for f in frames]
            for view, (cols, rows) in SIZES.items()
        }
        out = asset_dir / state
        out.mkdir(parents=True)
        for i, p in enumerate(paths):
            shutil.copyfile(p, out / f"{i}.png")
            shutil.copyfile(p.with_name(f"{p.stem}-bust.png"), out / f"{i}-bust.png")

    colours = np.array(
        [c for s in cells.values() for fs in s.values() for f in fs for _, fg, bg in f for c in (fg, bg) if c is not None],
        dtype=np.float32,
    )
    strip = Image.fromarray(np.clip(colours, 0, 255).astype(np.uint8).reshape(1, -1, 3), "RGB")
    raw = strip.quantize(PALETTE_COLORS, method=Image.Quantize.MEDIANCUT).getpalette()[: PALETTE_COLORS * 3]
    pal = np.array(raw, dtype=np.float32).reshape(-1, 3)

    def index(col) -> int:
        return 0 if col is None else int(((pal - col) ** 2).sum(axis=1).argmin()) + 1

    def encode(frame_cells) -> str:
        return base64.b64encode(bytes(v for m, fg, bg in frame_cells for v in (m, index(fg), index(bg)))).decode("ascii")

    data = {
        "palette": [(int(r) << 16) | (int(g) << 8) | int(b) for r, g, b in pal],
        "states": {st: {view: [encode(f) for f in fs] for view, fs in views.items()} for st, views in cells.items()},
    }
    ts = ROOT / "plugin" / "hooks" / "frames-extra.ts"
    ts.write_text(
        "// Generated by tools/build_extra.py from image26-v1; do not edit by hand.\n"
        "import type { ExtraSheet } from './sprite'\n\n"
        f"export const EXTRA: ExtraSheet = {json.dumps(data, separators=(',', ':'))}\n",
        encoding="utf-8",
    )
    png_kib = sum(p.stat().st_size for p in asset_dir.rglob("*.png")) // 1024
    print(f"extra: {len(ACTIONS)} actions, cells -> {ts.name} ({ts.stat().st_size // 1024} KiB), png -> assets/extra ({png_kib} KiB)")


if __name__ == "__main__":
    main()
